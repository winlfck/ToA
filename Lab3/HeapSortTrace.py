comparisons = 0
swaps = 0
 
 
def swap(arr, i, j):
    global swaps
    arr[i], arr[j] = arr[j], arr[i]
    swaps += 1
 
 
def sink(arr, i, n, building=True):
    global comparisons
    k = i
    phase = "Занурюємо" if building else "Відновлюємо купу для"
 
    while True:
        j = 2 * k + 1  # Індекс лівого дочірнього елемента
 
        if j >= n:
            print(f"  Елемент {arr[k]} на індексі {k} досяг кінця купи. Завершуємо.")
            break
 
        # Знаходимо найбільший дочірній елемент
        if j + 1 < n:
            comparisons += 1
            if arr[j + 1] > arr[j]:
                print(f"  Порівнюємо {arr[j]} (лівий) та {arr[j + 1]} (правий). Обираємо {arr[j + 1]}")
                j += 1
            else:
                print(f"  Обираємо лівий дочірній елемент: {arr[j]} на індексі {j}")
        else:
            print(f"  Обираємо лівий дочірній елемент: {arr[j]} на індексі {j}")
 
        # Порівнюємо поточний з найбільшим дочірнім
        comparisons += 1
        if arr[k] >= arr[j]:
            print(f"  {arr[k]} (батько) >= {arr[j]} (найбільший дочірній). Елемент на своєму місці.")
            break
        else:
            print(f"  Міняємо місцями {arr[k]} (батько) та {arr[j]} (дочірній)")
            swap(arr, k, j)
            print(f"  Масив після обміну: {arr[:n]}")
            k = j
 
 
def heapsort(arr):
    n = len(arr)
    print(f"Початковий масив: {arr}\n")
 
    # Фаза 1: Побудова максимальної купи
    print("--- Фаза 1: Побудова максимальної купи ---")
    for i in range(n // 2 - 1, -1, -1):
        print(f"Починаємо 'занурювати' елемент: {arr[i]} з індексу {i}")
        sink(arr, i, n, building=True)
        print("---------------------------------")
 
    print(f"\nМасив після побудови купи: {arr}\n")
 
    # Фаза 2: Сортування
    print("--- Фаза 2: Сортування ---")
    size = n
    for i in range(n - 1, 0, -1):
        print(f"Міняємо місцями корінь ({arr[0]}) та останній елемент ({arr[i]})")
        swap(arr, 0, i)
        size -= 1
        print(f"Розмір купи зменшився до {size}. Відновлюємо властивості купи.")
        print(f"Починаємо 'занурювати' елемент: {arr[0]} з індексу 0")
        sink(arr, 0, size, building=False)
        print(f"Масив на поточному кроці: {arr}\n")
 
    return arr
 
 
